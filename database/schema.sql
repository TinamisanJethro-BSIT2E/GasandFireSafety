CREATE TABLE IF NOT EXISTS public.readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  gas_value INTEGER NOT NULL,
  flame_detected INTEGER NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Normal', 'Gas Leak', 'Fire Detected')),
  fan_on INTEGER NOT NULL,
  pump_on INTEGER NOT NULL,
  buzzer_on INTEGER NOT NULL,
  regulator_open INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS idx_readings_created ON public.readings(created_at DESC);

CREATE TABLE IF NOT EXISTS public.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_type TEXT NOT NULL,
  gas_value INTEGER,
  actions TEXT NOT NULL DEFAULT '[]',
  details TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

CREATE INDEX IF NOT EXISTS idx_events_created ON public.events(created_at DESC);

ALTER TABLE public.readings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.readings, public.events FROM PUBLIC, anon, authenticated;
